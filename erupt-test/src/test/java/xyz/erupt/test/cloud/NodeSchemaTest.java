package xyz.erupt.test.cloud;

import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonPrimitive;
import org.junit.jupiter.api.Test;
import xyz.erupt.annotation.Erupt;
import xyz.erupt.annotation.EruptField;
import xyz.erupt.annotation.config.EruptProperty;
import xyz.erupt.annotation.config.Match;
import xyz.erupt.annotation.config.ToMap;
import xyz.erupt.linq.lambda.LambdaSee;

import java.beans.Transient;
import java.lang.annotation.Annotation;
import java.lang.reflect.Array;
import java.lang.reflect.Method;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayDeque;
import java.util.Arrays;
import java.util.Comparator;
import java.util.Deque;
import java.util.HashMap;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;

import static org.junit.jupiter.api.Assertions.assertEquals;

/**
 * Writes schema/erupt-annotations.schema.json: a JSON Schema of the JSON that
 * {@code AnnotationProcess.annotationToJsonByReflect} emits for {@code @Erupt}, {@code @EruptField} and every
 * annotation and enum they reach. Node SDKs in other languages generate their types from it, so an
 * annotation attribute added in Java reaches them by regenerating instead of by hand. Fails when the
 * committed file drifts; regenerate with
 * {@code mvn test -pl erupt-test -Dtest=NodeSchemaTest -Derupt.node-schema.write=true}.
 */
public class NodeSchemaTest {

    private static final Path FILE = Path.of("..", "schema", "erupt-annotations.schema.json");

    private static final Set<Class<?>> INTEGERS = Set.of(short.class, int.class, long.class);

    private static final Set<Class<?>> NUMBERS = Set.of(float.class, double.class);

    // byte and char serialize as strings, see AnnotationProcess.ANNOTATION_STRING_TYPE
    private static final Set<Class<?>> STRINGS = Set.of(String.class, byte.class, char.class, Class.class);

    private final Map<String, Class<?>> named = new HashMap<>();

    private final Map<String, JsonObject> defs = new TreeMap<>();

    @Test
    void nodeSchema() throws Exception {
        Deque<Class<?>> queue = new ArrayDeque<>(Arrays.asList(Erupt.class, EruptField.class));
        while (!queue.isEmpty()) {
            Class<?> type = queue.poll();
            String name = defName(type);
            if (defs.containsKey(name)) continue;
            defs.put(name, type.isEnum() ? enumDef(type) : annotationDef(type, queue));
        }
        // EruptModel.clone() swaps the extra class list for {annotation simple name: annotation JSON}
        JsonObject extra = new JsonObject();
        extra.addProperty("type", "object");
        extra.addProperty("description", "UI annotations on the class, keyed by simple name");
        defs.get(Erupt.class.getSimpleName()).getAsJsonObject("properties").add(LambdaSee.method(Erupt::extra), extra);
        JsonObject root = new JsonObject();
        root.addProperty("$schema", "https://json-schema.org/draft/2020-12/schema");
        root.addProperty("$id", "https://erupt.xyz/schema/erupt-annotations.schema.json");
        root.addProperty("title", "erupt annotation JSON");
        root.addProperty("description", "JSON emitted for erupt annotations in a build model. Generated by erupt-test NodeSchemaTest.");
        JsonArray roots = new JsonArray();
        roots.add(Erupt.class.getSimpleName());
        roots.add(EruptField.class.getSimpleName());
        root.add("x-erupt-roots", roots);
        JsonObject defsJson = new JsonObject();
        defs.forEach(defsJson::add);
        root.add("$defs", defsJson);
        String text = new GsonBuilder().setPrettyPrinting().disableHtmlEscaping().create().toJson(root) + "\n";
        if (Boolean.getBoolean("erupt.node-schema.write")) {
            Files.createDirectories(FILE.getParent());
            Files.writeString(FILE, text, StandardCharsets.UTF_8);
        } else {
            assertEquals(text, Files.readString(FILE, StandardCharsets.UTF_8),
                    FILE + " is stale, regenerate with -Derupt.node-schema.write=true");
        }
    }

    // Nested types are named after their enclosing types (RowOperation.Mode -> RowOperationMode)
    private String defName(Class<?> type) {
        StringBuilder name = new StringBuilder(type.getSimpleName());
        for (Class<?> outer = type.getEnclosingClass(); null != outer; outer = outer.getEnclosingClass()) {
            name.insert(0, outer.getSimpleName());
        }
        Class<?> clash = named.putIfAbsent(name.toString(), type);
        if (null != clash && clash != type) {
            throw new IllegalStateException("Two types named " + name + ": " + clash + ", " + type);
        }
        return name.toString();
    }

    private JsonObject enumDef(Class<?> type) {
        JsonObject def = new JsonObject();
        def.addProperty("type", "string");
        JsonArray values = new JsonArray();
        for (Object constant : type.getEnumConstants()) values.add(constant.toString());
        def.add("enum", values);
        return def;
    }

    private JsonObject annotationDef(Class<?> type, Deque<Class<?>> queue) {
        JsonObject properties = new JsonObject();
        JsonArray required = new JsonArray();
        Method[] methods = type.getDeclaredMethods();
        Arrays.sort(methods, Comparator.comparing(Method::getName));
        for (Method method : methods) {
            Transient tran = method.getAnnotation(Transient.class);
            if (null != tran && tran.value()) continue;
            EruptProperty property = method.getAnnotation(EruptProperty.class);
            String name = null != property && !property.alias().isEmpty() ? property.alias() : method.getName();
            Class<?> returnType = method.getReturnType();
            JsonObject schema;
            boolean present = true;
            if (returnType.isArray()) {
                Class<?> element = returnType.getComponentType();
                ToMap toMap = method.getAnnotation(ToMap.class);
                if (null != toMap) {
                    // keyed by toMap.key(), which is dropped from each value; absent while empty
                    schema = new JsonObject();
                    schema.addProperty("type", "object");
                    schema.add("additionalProperties", valueSchema(element, queue));
                    schema.addProperty("x-erupt-map-key", toMap.key());
                    present = false;
                } else {
                    schema = new JsonObject();
                    schema.addProperty("type", "array");
                    schema.add("items", valueSchema(element, queue));
                }
            } else {
                schema = valueSchema(returnType, queue);
            }
            Match match = method.getAnnotation(Match.class);
            if (null != match) {
                // emitted only while the SpEL condition holds
                schema.addProperty("x-erupt-match", match.value());
                present = false;
            }
            JsonElement defaultValue = defaultValue(method.getDefaultValue());
            if (null != defaultValue && null == method.getAnnotation(ToMap.class)) schema.add("default", defaultValue);
            properties.add(name, schema);
            if (present) required.add(name);
        }
        JsonObject def = new JsonObject();
        def.addProperty("type", "object");
        def.add("properties", properties);
        if (!required.isEmpty()) def.add("required", required);
        def.addProperty("additionalProperties", false);
        return def;
    }

    private JsonObject valueSchema(Class<?> type, Deque<Class<?>> queue) {
        JsonObject schema = new JsonObject();
        if (type.isAnnotation() || type.isEnum()) {
            queue.add(type);
            schema.addProperty("$ref", "#/$defs/" + defName(type));
        } else if (STRINGS.contains(type)) {
            schema.addProperty("type", "string");
        } else if (INTEGERS.contains(type)) {
            schema.addProperty("type", "integer");
        } else if (NUMBERS.contains(type)) {
            schema.addProperty("type", "number");
        } else if (boolean.class == type) {
            schema.addProperty("type", "boolean");
        } else {
            throw new IllegalStateException("Unmapped annotation attribute type " + type);
        }
        return schema;
    }

    // Literal defaults only; a nested annotation's default is described by its own definition
    private JsonElement defaultValue(Object value) {
        if (null == value || value instanceof Annotation) return null;
        if (value.getClass().isArray()) {
            JsonArray array = new JsonArray();
            for (int i = 0; i < Array.getLength(value); i++) {
                JsonElement item = defaultValue(Array.get(value, i));
                if (null == item) return null;
                array.add(item);
            }
            return array;
        }
        if (value instanceof Boolean b) return new JsonPrimitive(b);
        if (value instanceof Number n) return new JsonPrimitive(n);
        if (value instanceof Class<?> c) return new JsonPrimitive(c.getSimpleName());
        return new JsonPrimitive(value.toString());
    }

}
